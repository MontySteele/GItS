/// <summary>
/// EVERY KIT'S CARD COLOUR, IN ONE PLACE (card frames stage 1, 2026-10-19).
///
/// [USER], 2026-10-19: "we need a quick way of distinguishing the character
/// cards". Furina, Kokomi and Varka all wore the Silent's green frame, Klee
/// the Ironclad's red and Yae the Defect's blue, so a kit card looked like a
/// base character's card and like each other's.
///
/// HOW THE TINT IS DRAWN. The base game draws every character card from one
/// frame texture per card type (crimson, `card_frame_attack_s` and siblings)
/// and recolours it with a per-pool material: `res://shaders/hsv.gdshader`,
/// whose `h` rotates hue in YIQ space by (1 - h) of a turn, `s` scales the
/// chroma and `v` scales brightness. The base materials, read out of
/// SlayTheSpire2.pck 2026-10-19, are Ironclad 0.025/0.85/1.0, Regent
/// 0.12/1.5/1.2, Silent 0.32/0.45/1.2, Defect 0.55/0.9/1.0, Necrobinder
/// 0.965/0.55/1.2, Colorless 1.0/0.0/1.2. BaseLib builds the same material
/// from a <see cref="CustomCardPoolModel"/>'s H, S and V when the pool keeps
/// the path `card_frame_red` (<see cref="KitCardPool"/>); the numbers below
/// were chosen against a render of that shader on the shipped frame so that
/// no kit sits on a base character's hue.
///
/// <see cref="Tint.DeckEntry"/> is the deck-entry chip colour (the base pools
/// use a saturated version of their frame hue, Ironclad D62000);
/// <see cref="Tint.EnergyOutline"/> outlines the cost number on the orb.
///
/// STAGE 2 (2026-10-20, [USER]: "Agreed on all of the card / orb / energy
/// mockup picks, including Kokomi's (b)"):
/// <list type="bullet">
/// <item>Each kit's CARD COST ORB is the base Ironclad cost orb recoloured
/// through that kit's own (h, s, v) below, generated by
/// <c>tools/gen_kit_energy_icons.py</c> (which reads this file for the
/// numbers) and served through BaseLib's custom energy-icon hook
/// (<see cref="KitCardPool.BigEnergyIconPath"/>).
/// <see cref="Tint.BorrowedEnergy"/> is the base orb each kit wore before,
/// kept as the fallback for a pck without the new icons.</item>
/// <item>Shared COMPANION cards split their frame: Colorless on the left,
/// the nation's tint (<see cref="NationTint"/>) on the right
/// (<see cref="KleeMod.Vfx.CompanionSplitFrame"/>).</item>
/// </list>
/// </summary>
public static class CardFrameColors
{
    /// <summary>One kit's frame tint: the hsv shader's three parameters plus
    /// the two flat colours the pool also controls.</summary>
    public readonly record struct Tint(
        string Kit, float H, float S, float V, Color DeckEntry, Color EnergyOutline,
        string BorrowedEnergy)
    {
        /// <summary>The kit's card cost orb (stage 2), in its own namespace.</summary>
        public string CostOrbPath => $"{Kit}/ui/energy_cost.png";

        /// <summary>The small orb rich text draws inline ("Gain [orb]").</summary>
        public string TextIconPath => $"{Kit}/ui/energy_text_icon.png";

        /// <summary>The kit's combat energy counter (stage 2), Furina's shape.</summary>
        public string EnergyCounterPath => $"{Kit}/ui/energy_counter.tscn";
    }

    /// <summary>Warm red-orange (renders about #C44A00), between the
    /// Ironclad's red and the Regent's amber.</summary>
    public static readonly Tint Klee =
        new("klee", 0.065f, 1.3f, 1.15f, new Color("F0600F"), new Color("7A3010"), "ironclad");

    /// <summary>Deep blue (about #2348B7), darker and more violet than the
    /// Defect's cyan-blue.</summary>
    public static readonly Tint Furina =
        new("furina", 0.63f, 1.1f, 0.85f, new Color("2F5BE0"), new Color("1A2A70"), "silent");

    /// <summary>Pearl coral (about #B27768): pale and low-saturation, so it
    /// reads apart from both the Ironclad's red and the Necrobinder's pink.</summary>
    public static readonly Tint Kokomi =
        new("kokomi", 0.03f, 0.38f, 1.55f, new Color("E89A86"), new Color("7A3E34"), "silent");

    /// <summary>Anemo teal-green (about #12805B), bluer than the Silent's
    /// leaf green.</summary>
    public static readonly Tint Varka =
        new("varka", 0.47f, 0.9f, 1.05f, new Color("1FB585"), new Color("0F5A40"), "silent");

    /// <summary>Magenta-pink (about #AD33A0), more saturated and more violet
    /// than the Necrobinder's dusty pink.</summary>
    public static readonly Tint Yae =
        new("yae", 0.9f, 0.9f, 1.15f, new Color("D63CC8"), new Color("6B1F63"), "defect");

    public static readonly Tint[] All = { Klee, Furina, Kokomi, Varka, Yae };

    // ---- stage 2: the companions' split frame (2026-10-20) -----------------

    /// <summary>The base Colorless frame material
    /// (<c>card_frame_colorless_mat.tres</c>): the left side of a split frame.</summary>
    public const float ColorlessH = 1.0f;

    public const float ColorlessS = 0.0f;

    public const float ColorlessV = 1.2f;

    /// <summary>The split's geometry, as a fraction of the frame's width: pure
    /// Colorless up to <see cref="SplitStart"/>, a smoothstep blend over
    /// <see cref="SplitWidth"/>, pure nation tint after (the "soft blend" pick).</summary>
    public const float SplitStart = 0.40f;

    public const float SplitWidth = 0.20f;

    /// <summary>One nation's frame tint, in the same hsv-shader terms as a kit's.</summary>
    public readonly record struct NationTint(string Nation, float H, float S, float V);

    /// <summary>M-A, pale sky-aqua (tint side about #3F7F88): Anemo, but less
    /// than half Varka's chroma and much lighter, since Varka's own frame is
    /// the Anemo teal.</summary>
    public static readonly NationTint Mondstadt = new("mondstadt", 0.52f, 0.45f, 1.45f);

    /// <summary>I-A, Electro violet (about #722CE7), 0.13 of a turn from
    /// Yae's magenta.</summary>
    public static readonly NationTint Inazuma = new("inazuma", 0.77f, 1.0f, 1.15f);

    /// <summary>F-A, pale steel blue (about #5E67B5): Furina's hue family at
    /// a third of her chroma, much lighter.</summary>
    public static readonly NationTint Fontaine = new("fontaine", 0.66f, 0.40f, 1.45f);

    /// <summary>The nations that have shared Companions. Liyue has a pip
    /// colour but no companion yet, so no frame tint either.</summary>
    public static readonly NationTint[] Nations = { Mondstadt, Inazuma, Fontaine };

    /// <summary>The tint for a companion's declared nation, or null (no split).</summary>
    public static NationTint? NationFor(string? nation)
    {
        foreach (var tint in Nations)
        {
            if (tint.Nation == nation)
            {
                return tint;
            }
        }

        return null;
    }
}

/// <summary>
/// A kit's card pool, tinted by BaseLib's HSV frame material
/// (<see cref="CardFrameColors"/>).
///
/// WHY A <see cref="CustomCardPoolModel"/> NOW. BaseLib's material patch
/// replaces <c>CardPoolModel.FrameMaterial</c> only for its own pool type,
/// and only while the path stays <c>card_frame_red</c>, which is therefore
/// sealed here. Everything else about the five pools is unchanged:
/// <list type="bullet">
/// <item>ID. A <c>CustomCardPoolModel</c> is an <c>ICustomModel</c>, and
/// BaseLib's <c>PrefixIdPatch</c> prefixes such a type's ModelId entry with
/// its namespace. Each subclass pins its old entry with <c>[CustomID]</c>
/// (the game's own <c>StringHelper.Slugify</c> of the type name), so
/// <c>KLEE_CARD_POOL</c> stays <c>KLEE_CARD_POOL</c>.</item>
/// <item>Membership and offer: the subclasses' own GenerateAllCards and
/// FilterThroughEpochs, untouched.</item>
/// <item>IsShared false, so nothing registers it as a shared pool;
/// SeenByDefault false, so the library's mark-as-seen patch skips it;
/// CustomFrame returns null, so the per-type frame texture stays the base
/// one (stage 2 is where that changes).</item>
/// <item>The energy orb (stage 2, 2026-10-20): <see cref="EnergyColorName"/>
/// is BaseLib's own id-derived name again (no subclass borrows a base name any
/// more), which is what routes <c>EnergyIconHelper.GetPath</c> and the rich
/// text <c>energyIcons</c> formatter to <see cref="BigEnergyIconPath"/> and
/// <see cref="TextEnergyIconPath"/>. Both fall back to the base orb the kit
/// used to borrow when the pck lacks the kit's file, so a stale pck shows the
/// old orb rather than a broken path. The kit's relic and potion pools answer
/// the same name (<see cref="KitEnergyIcon.NameOf{TPool}"/>), so their
/// tooltips draw the same orb.</item>
/// </list>
/// </summary>
public abstract class KitCardPool : CustomCardPoolModel
{
    /// <summary>This kit's row in <see cref="CardFrameColors"/>.</summary>
    public abstract CardFrameColors.Tint Tint { get; }

    public sealed override string CardFrameMaterialPath => "card_frame_red";

    public sealed override float H => Tint.H;

    public sealed override float S => Tint.S;

    public sealed override float V => Tint.V;

    /// <summary>Not read by BaseLib once H, S and V are given (they are what it
    /// derives from this colour, and S and V above 1 cannot be written as a
    /// colour); kept as the chip swatch so the two cannot disagree.</summary>
    public sealed override Color ShaderColor => Tint.DeckEntry;

    public sealed override Color DeckEntryCardColor => Tint.DeckEntry;

    public sealed override Color EnergyOutlineColor => Tint.EnergyOutline;

    /// <summary>BaseLib's <c>id.Category + "∴" + id.Entry</c>; sealed so no
    /// kit can borrow a base orb by name again (a base name bypasses the hook).</summary>
    public sealed override string EnergyColorName => base.EnergyColorName;

    /// <summary>The cost orb on the card face and in energy hover tips.</summary>
    public sealed override string? BigEnergyIconPath =>
        KleePck.Path(Tint.CostOrbPath) ?? KitEnergyIcon.BaseCostOrb(Tint.BorrowedEnergy);

    /// <summary>The inline orb in card, relic, potion and power text.</summary>
    public sealed override string? TextEnergyIconPath =>
        KleePck.Path(Tint.TextIconPath) ?? KitEnergyIcon.BaseTextIcon(Tint.BorrowedEnergy);

    public sealed override bool IsShared => false;

    public sealed override bool IsColorless => false;
}

/// <summary>The base game's own energy-icon paths, as
/// <c>EnergyIconHelper.GetPath(string)</c> and <c>EnergyIconsFormatter</c>
/// spell them, and the name a kit's relic and potion pools answer.</summary>
public static class KitEnergyIcon
{
    /// <summary>A base cost orb (<c>energy_ironclad</c> and siblings).</summary>
    public static string BaseCostOrb(string baseName) =>
        $"res://images/atlases/ui_atlas.sprites/card/energy_{baseName}.tres";

    /// <summary>A base inline text orb.</summary>
    public static string BaseTextIcon(string baseName) =>
        $"res://images/packed/sprite_fonts/{baseName}_energy_icon.png";

    /// <summary>A kit card pool's energy name. A relic or potion pool answers
    /// this so BaseLib's hook resolves its icons through the kit card pool
    /// (the <see cref="ICustomEnergyIconPool"/>), the way
    /// <c>EnergyIconHelper.GetPool</c> already does for an owned relic.</summary>
    public static string NameOf<TPool>() where TPool : KitCardPool =>
        ModelDb.CardPool<TPool>().EnergyColorName;
}

/// <summary>
/// BORROWED BASICS WEAR THE KIT'S FRAME (2026-10-20).
///
/// [USER], 2026-10-20: "All of the Strikes and Defends in Kokomi's deck still
/// have the Silent's green border. Can we make those mirror the color of the
/// cards in her deck, and do the same for other characters?"
///
/// Every kit starts on the BASE game's Strike and Defend (StrikeSilent for
/// Furina, Kokomi and Varka, StrikeIronclad for Klee, StrikeDefect for Yae),
/// and those stay the exact base cards. Their <c>Pool</c> is the base
/// character's, and the frame, the tiny-card back and the orb all read
/// <c>CardModel.VisualCardPool</c> (base body: <c>=&gt; Pool</c>). This postfix
/// answers the owner's kit pool instead, for a Basic card whose own pool is
/// not a kit pool and whose owner plays a kit. Nothing else moves:
/// <list type="bullet">
/// <item>A canonical card (library, compendium) has no owner, so it keeps the
/// base colour. Ownership is read the way the base game's own
/// <c>EnergyIconHelper.GetPool</c> reads it: <c>IsMutable</c> first, since
/// <c>Owner</c> asserts mutability.</item>
/// <item>A kit's own Basic cards already sit in their kit pool and are
/// skipped; a card whose class overrides VisualCardPool (Clash, Caltrops, ...)
/// never runs this body.</item>
/// <item>Gameplay: the only game read that is not paint is Heirloom Hammer's
/// <c>VisualCardPool.IsColorless</c>, false on a kit pool as on a base
/// character pool. The orb is the kit pool's own (stage 2), and the cost
/// number's outline follows <c>VisualCardPool</c> too
/// (<see cref="NCard_EnergyOutline_VisualPool_Patch"/>).</item>
/// <item>Co-op: the tint follows the card's owner, so each player's basics
/// wear that player's kit.</item>
/// </list>
/// </summary>
[HarmonyPatch(typeof(CardModel), "get_VisualCardPool")]
internal static class CardModel_VisualCardPool_KitBasics_Patch
{
    private static void Postfix(CardModel __instance, ref CardPoolModel __result)
    {
        try
        {
            var ownerPool = __instance.IsMutable
                ? __instance.Owner?.Character?.CardPool
                : null;
            __result = BorrowedBasicFrame.PoolFor(__instance.Rarity, __result, ownerPool);
        }
        catch
        {
            // A mid-teardown owner or a card with no pool: the base answer stands.
        }
    }
}

/// <summary>The decision <see cref="CardModel_VisualCardPool_KitBasics_Patch"/>
/// makes, apart from the card so it can be tested without a run.</summary>
public static class BorrowedBasicFrame
{
    /// <summary>The pool a card is drawn with: the owner's kit pool for a
    /// borrowed Basic, otherwise <paramref name="visual"/> unchanged.</summary>
    public static CardPoolModel PoolFor(
        CardRarity rarity, CardPoolModel visual, CardPoolModel? ownerPool) =>
        rarity == CardRarity.Basic
        && visual is not KitCardPool
        && ownerPool is KitCardPool kit
            ? kit
            : visual;
}

/// <summary>
/// THE COST NUMBER'S OUTLINE FOLLOWS THE DRAWN POOL (card frames stage 2,
/// 2026-10-20).
///
/// <c>NCard.UpdateEnergyCostColor</c> (and the hidden-card branch of
/// <c>UpdateEnergyCostVisuals</c>) outline the cost number in
/// <c>Model.Pool.EnergyOutlineColor</c>, while the frame and the orb are drawn
/// from <c>Model.VisualCardPool</c>. For a borrowed Strike or Defend
/// (<see cref="CardModel_VisualCardPool_KitBasics_Patch"/>) the two differ, so
/// the kit-coloured orb carried the base character's outline. When the label
/// holds that default outline (not a cost-change green or blue, nor the
/// unplayable red, which the base game picks on top of it) this swaps it for
/// the drawn pool's. A card whose two pools agree is untouched.
/// </summary>
[HarmonyPatch]
internal static class NCard_EnergyOutline_VisualPool_Patch
{
    private static readonly AccessTools.FieldRef<NCard, MegaLabel> EnergyLabel =
        AccessTools.FieldRefAccess<NCard, MegaLabel>("_energyLabel");

    private static readonly StringName Outline = "font_outline_color";

    [HarmonyPostfix]
    [HarmonyPatch(typeof(NCard), "UpdateEnergyCostColor")]
    private static void AfterColor(NCard __instance) => Swap(__instance);

    [HarmonyPostfix]
    [HarmonyPatch(typeof(NCard), "UpdateEnergyCostVisuals")]
    private static void AfterVisuals(NCard __instance) => Swap(__instance);

    private static void Swap(NCard card)
    {
        try
        {
            var model = card.Model;
            if (model == null)
            {
                return;
            }

            var visual = model.VisualCardPool;
            var own = model.Pool;
            var label = EnergyLabel(card);
            if (label == null)
            {
                return;
            }

            var swapped = OutlineFor(label.GetThemeColor(Outline), own.EnergyOutlineColor,
                                     visual.EnergyOutlineColor);
            if (swapped is { } color)
            {
                label.AddThemeColorOverride(Outline, color);
            }
        }
        catch
        {
            // A pooled card mid-teardown: the base outline stands.
        }
    }

    /// <summary>The outline to put on, or null to leave the label alone: only
    /// the pool's own default outline is replaced, and only by a different one.</summary>
    internal static Color? OutlineFor(Color current, Color poolDefault, Color visualDefault) =>
        current == poolDefault && visualDefault != poolDefault ? visualDefault : null;
}
