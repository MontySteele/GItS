    from tier0.harness import report
    report.print_card_flow("punisher", metrics.card_flow_profile(_battery()))
    out = capsys.readouterr().out
    assert "card flow" in out
    assert "dead" in out and "pwd" in out and "first-copy" in out
    for word in ("VERDICT", "FAIL", "dead card", "redesign"):
        assert word not in out


