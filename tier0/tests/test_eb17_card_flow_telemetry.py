# --- 1: played-when-drawn ------------------------------------------------

def test_played_when_drawn_fires_on_a_card_played_the_turn_it_arrived():
    st = _fight([_card("poke", damage=3)], plays=[["poke"]])
    s = _stats(st)
    assert s.card_draws == {"poke": 1}
    assert s.card_plays == {"poke": 1}
    assert s.played_when_drawn == {"poke": 1}


def test_played_when_drawn_stays_zero_for_a_card_played_a_later_turn():
    """A Retained card survives the flush and is played on turn 2. It was
    drawn on turn 1, so it is a play and NOT a played-when-drawn -- which is
    the entire distinction a per-id tally over the event stream cannot make."""
    st = _fight([_card("slow_burn", damage=3, retain=True)],
                plays=[[], ["slow_burn"]])
    s = _stats(st)
    assert s.card_draws == {"slow_burn": 1}      # drawn once, turn 1
    assert s.card_plays == {"slow_burn": 1}      # played once, turn 2
    assert s.played_when_drawn == {}


def test_played_when_drawn_stays_zero_for_a_card_that_never_came_from_a_draw():
    """A kit Burst is granted to hand, never drawn. Playing it is a play with
    no draw behind it, and -1 is the honest draw turn -- it must never collide
    with a real turn number."""
    st = make_state(enemies=[make_enemy(hp=200)])
    st.turn = 3
    burst = _card("kit_burst", damage=5, tags=["burst"], kit_card=True)
    st.player.hand.append(burst)
    combat.play_card(st, burst)
    s = _stats(st)
    assert s.card_plays == {"kit_burst": 1}
    assert s.played_when_drawn == {}
    play = [e for e in st.log if e["event"] == "play"][0]
    assert play["drawn_turn"] == -1


# --- 2: dead-in-hand -----------------------------------------------------

def test_dead_in_hand_fires_on_a_card_the_flush_threw_away_unplayed():
    st = _fight([_card("dud", cost=9)], plays=[[]])
    s = _stats(st)
    assert s.card_draws == {"dud": 1}
    assert s.card_plays == {}
    assert s.dead_in_hand == {"dud": 1}
    row = [e for e in st.log if e["event"] == "dead_in_hand"]
    assert [(e["card"], e["reason"], e["drawn_turn"]) for e in row] == \
        [("dud", "flush", 1)]


def test_dead_in_hand_stays_zero_for_a_card_that_was_played():
    """The negative of the case above, one card apart: the same fight with
    the card playable and played."""
    st = _fight([_card("live", damage=3)], plays=[["live"]])
    s = _stats(st)
    assert s.dead_in_hand == {}
    assert not [e for e in st.log if e["event"] == "dead_in_hand"]


def test_dead_in_hand_counts_a_retained_card_only_once_the_combat_ends_on_it():
    """Retention is not death. A Retained dud survives two flushes without
    being counted, and is counted exactly once -- at fight end -- when the
    combat finishes with it still sitting in hand."""
    finisher = _card("finisher", damage=50)
    dud = _card("retained_dud", cost=9, retain=True)
    player = Player(hp=200, max_hp=200, draw_pile=[finisher, dud])
    enemy = Enemy(hp=5, max_hp=5, name="paper",
                  intents=[{"kind": "block", "amount": 0}])

    def pilot(s):
        for c in s.player.hand:
            if c.id == "finisher":
                return c
        return None

    st = combat.run_fight(player, [enemy], pilot, seed=1)
    s = _stats(st)
    assert st.player.hand and st.player.hand[0].id == "retained_dud"
    assert s.dead_in_hand == {"retained_dud": 1}
    assert [e["reason"] for e in st.log
            if e["event"] == "dead_in_hand"] == ["fight_end"]


def test_a_card_that_was_never_drawn_is_never_dead_in_hand():
    """A token put straight into hand and left there is not a DRAWN instance,
    so it is outside this counter's denominator (`card_draws`) and outside its
    numerator. Counting it would make the rate uninterpretable."""
    st = make_state(enemies=[make_enemy(hp=200)])
    st.player.hand.append(_card("token", cost=9))
    combat._player_turn(st, lambda s: None)
    s = _stats(st)
    assert "token" not in s.card_draws
    assert s.dead_in_hand == {}


# --- 3: force-first-copy -------------------------------------------------

def test_force_first_copy_fires_when_the_first_copy_drawn_is_played():
    st = _fight([_card("probe", damage=3), _card("probe", damage=3)],
                plays=[["probe"]])
    s = _stats(st)
    assert s.force_first_copy_drawn == {"probe": 1}
    assert s.force_first_copy == {"probe": 1}


def test_force_first_copy_stays_zero_when_only_a_later_copy_is_played():
    """Two copies in hand, and the SECOND one is the one that gets played.
    The first copy was drawn and did nothing, so the conversion is 0 out of a
    denominator of 1 -- the number the register's forced-copy arm is read
    against. A per-id tally would have scored this 1."""
    first, second = _card("probe", damage=3), _card("probe", damage=3)
    st = make_state(enemies=[make_enemy(hp=200)])
    st.turn = 1
    st.player.draw_pile = [first, second]
    st.draw(2)
    assert st.player.hand == [first, second]
    combat.play_card(st, second)
    s = _stats(st)
    assert s.card_draws == {"probe": 2}
    assert s.card_plays == {"probe": 1}
    assert s.force_first_copy_drawn == {"probe": 1}
    assert s.force_first_copy == {}


def test_force_first_copy_is_absent_when_the_copy_was_never_drawn():
    """Never drawn is not failed-to-convert. Absent, not zero: the deck held
    the card and the fight never saw it, which is a different finding."""
    st = _fight([_card("poke", damage=3)] * C.CARDS_DRAWN_PER_TURN
                + [_card("buried", cost=9)], plays=[["poke"]])
    s = _stats(st)
    assert "buried" not in s.card_draws
    assert "buried" not in s.force_first_copy_drawn
    assert "buried" not in s.force_first_copy


def test_the_first_copy_stays_the_first_copy_across_a_redraw():
    """The forced copy is a COPY, not a turn. Drawn, put back, drawn again and
    played, it is still the first copy that converted -- and its twin, drawn
    in between, is still not."""
    first, second = _card("probe", damage=3), _card("probe", damage=3)
    st = make_state(enemies=[make_enemy(hp=200)])
    st.turn = 1
    st.player.draw_pile = [first, second]
    st.draw(2)
    st.player.hand.remove(first)
    st.player.draw_pile.append(first)
    st.turn = 2
    st.draw(1)
    assert st.player.hand[-1] is first
    combat.play_card(st, first)
    s = _stats(st)
    assert s.card_draws == {"probe": 3}
    assert s.force_first_copy == {"probe": 1}
    assert s.played_when_drawn == {"probe": 1}      # drawn AND played on 2


# --- 4: invariants over a real battery -----------------------------------

KLEE = ("klee", "reaction_weighted", "punisher", "reaction")


def _battery(fights=30, seed=7):
    return run_battery(*KLEE, fights, seed)


def test_played_when_drawn_never_exceeds_plays():
    for s in _battery():
        for cid, n in s.played_when_drawn.items():
            assert n <= s.card_plays[cid], cid


def test_played_when_drawn_plus_dead_in_hand_never_exceeds_draws():
    """Each counted play and each counted death consumes one draw of that id,
    and a draw can be consumed once. They do NOT sum to the draws: a card
    Retained into a later turn, or pulled out of hand by a discard or exhaust
    op, is a third outcome and belongs to neither."""
    for s in _battery():
        for cid in set(s.played_when_drawn) | set(s.dead_in_hand):
            assert (s.played_when_drawn.get(cid, 0)
                    + s.dead_in_hand.get(cid, 0)) <= s.card_draws.get(cid, 0), cid


def test_the_first_copy_pair_is_a_zero_or_one_indicator_per_combat():
    for s in metrics.per_combat(_battery()):
        assert set(s.force_first_copy.values()) <= {1}
        assert set(s.force_first_copy_drawn.values()) <= {1}
        for cid in s.force_first_copy:
            assert s.force_first_copy_drawn.get(cid) == 1, cid


def test_cards_played_agrees_with_the_per_card_play_tally():
    for s in _battery():
        assert sum(s.card_plays.values()) == s.cards_played


# --- 5: the aggregate hook ------------------------------------------------

def test_card_flow_profile_pools_and_reports_no_verdict():
    stats = _battery()
    prof = metrics.card_flow_profile(stats)
    combats = metrics.per_combat(stats)
    assert prof["draws"] == sum(sum(s.card_draws.values()) for s in combats)
    assert prof["plays"] == sum(sum(s.card_plays.values()) for s in combats)
    assert prof["dead_in_hand"] == sum(sum(s.dead_in_hand.values())
                                       for s in combats)
    # No grade, no band, no pass/fail -- the track D/H fence, restated.
    for key in ("verdict", "grade", "ok", "healthy", "band", "target",
                "dead_card"):
        assert key not in prof


def test_card_flow_profile_is_empty_not_exploding_on_no_fights():
    assert metrics.card_flow_profile([]) == {}


def test_card_flow_profile_keeps_an_undefined_rate_out_of_the_numbers():
    """A card whose first copy was never drawn has no conversion rate, and
    the split winrates over an empty arm are None rather than 0.0. Printing
    0% for 'never happened' is how a report gets misread."""
    stats = _battery()
    prof = metrics.card_flow_profile(stats)
    for cid, row in prof["by_card"].items():
        if row["first_copy_drawn_combats"] == 0:
            assert row["force_first_copy_rate"] is None, cid
            assert row["winrate_first_copy_played"] is None, cid
            assert row["winrate_first_copy_dead"] is None, cid
        else:
            assert 0.0 <= row["force_first_copy_rate"] <= 1.0, cid


def test_card_flow_profile_denominates_over_combats():
    stats = _battery()
    prof = metrics.card_flow_profile(stats)
    assert prof["combats"] == len(metrics.per_combat(stats))
    for cid, row in prof["by_card"].items():
        assert row["draws_per_fight"] == row["draws"] / prof["combats"], cid


def test_the_winrate_split_covers_exactly_the_combats_that_drew_the_copy():
    """The forced-copy arm's read: every combat that DREW the first copy lands
    in one of the two winrate arms, and no combat that did not draw it lands
    in either."""
    stats = _battery()
    combats = metrics.per_combat(stats)
    prof = metrics.card_flow_profile(stats)
    for cid, row in prof["by_card"].items():
        drew = [s for s in combats if s.force_first_copy_drawn.get(cid)]
        assert len(drew) == row["first_copy_drawn_combats"], cid
        converted = [s for s in drew if s.force_first_copy.get(cid)]
        assert len(converted) == row["force_first_copy"], cid


def test_a_gauntlet_record_ors_the_first_copy_indicator_instead_of_summing():
    """O-1: a `gauntlet` is one record and two combats, each drawing its own
    deck. Summing the two 0/1 stage values would read as two conversions out
    of a denominator of one."""
    a = metrics.extract(_fight([_card("probe", damage=3)],
                               plays=[["probe"]]), 200)
    b = metrics.extract(_fight([_card("probe", damage=3)],
                               plays=[["probe"]]), 200)
    merged = metrics.merge_stages([a, b])
    assert merged.force_first_copy == {"probe": 1}
    assert merged.force_first_copy_drawn == {"probe": 1}
    assert merged.card_draws == {"probe": 2}        # counts DO sum
    assert merged.stages == [a, b]


