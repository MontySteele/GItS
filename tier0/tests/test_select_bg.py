def test_one_producer_build_pck_no_longer_writes_the_select_scenes(char):
    ps = BUILD.read_text(encoding="utf-8")
    assert f"'{char}\\ui\\char_select_bg_{char}.tscn'" not in ps
    assert f"${char}SelectArt" not in ps
    # the pack consumes the generated scene through the pck-src overlay, and
    # refuses to build without the close-up it draws
    assert "Copy-Item (Join-Path $pckSrc '*') -Destination $work -Recurse -Force" in ps
    closeup = "ui\\select_closeup.png" if char == "klee" else f"{char}\\ui\\select_closeup.png"
    assert f"'{closeup}'" in ps.split("foreach ($closeup in @(", 1)[1].split(")", 1)[0]


