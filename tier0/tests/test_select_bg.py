"""The animated character-select scenes of Klee, Varka and Furina (stage 1).

[USER], 2026-10-14: "during character select, none of the art pieces for the
base game's characters are static; the character does a small idle loop with
particle effects. Let's investigate if we could do the same somehow for our
characters, focusing on Klee, Varka and Furina".

klee-mod/pck-src/<char>/ui/char_select_bg_<char>.tscn are GENERATED by each
kit's rig generator through tools/select_bg.py. These tests hold, without art
or engine:

  * the shipped scene is what its rig writes, byte-identically;
  * the close-up breathes on an AnimationPlayer that autoplays a looping clip;
  * two to five CPUParticles2D emitters in the element's shape, at base-game
    counts, with no script and no base-game texture;
  * one producer: build_pck.ps1 no longer writes these paths.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

from tools import select_bg
from tools.furina_rig import rig as furina_rig
from tools.klee_rig import rig as klee_rig
from tools.varka_rig import rig as varka_rig

ROOT = Path(__file__).resolve().parents[2]
BUILD = ROOT / "tools" / "build_pck.ps1"

RIGS = {"klee": klee_rig, "varka": varka_rig, "furina": furina_rig}
ELEMENT = {"klee": "pyro", "varka": "anemo", "furina": "hydro"}
#: Emitter names each element must carry (the brief: Pyro embers/sparks,
#: Anemo streaks + leaves, Hydro droplets/bubbles).
EMITTERS = {"pyro": {"Embers", "Sparks"}, "anemo": {"Streaks", "Leaves"}, "hydro": {"Bubbles", "Droplets"}}


@pytest.fixture(scope="module", params=sorted(RIGS))
def char(request) -> str:
    return request.param


def _text(char: str) -> str:
    return RIGS[char].SELECT_SCENE.read_text(encoding="utf-8")


def _node(text: str, name: str) -> str:
    return text.split(f'[node name="{name}"', 1)[1].split("\n[", 1)[0]


def _emitters(text: str) -> dict[str, str]:
    return {m.group(1): _node(text, m.group(1))
            for m in re.finditer(r'\[node name="([^"]+)" type="CPUParticles2D"', text)}


def test_the_shipped_scene_is_what_its_rig_writes(char):
    rig = RIGS[char]
    assert rig.SELECT_SCENE == ROOT / "klee-mod" / "pck-src" / char / "ui" / f"char_select_bg_{char}.tscn"
    assert rig.render_select_scene() == rig.render_select_scene() == _text(char), \
        f"stale: run `python -m tools.{char}_rig gen`"


def test_the_close_up_breathes_on_an_autoplaying_loop(char):
    text = _text(char)
    player = _node(text, "AnimationPlayer")
    assert 'type="AnimationPlayer" parent="."' in player
    assert f'autoplay = "{select_bg.ANIMATION}"' in player
    clip = text.split('[sub_resource type="Animation" id="Animation_select_idle"]', 1)[1].split("\n[", 1)[0]
    assert f'resource_name = "{select_bg.ANIMATION}"' in clip
    assert "loop_mode = 1" in clip
    length = float(re.search(r"length = ([\d.]+)", clip).group(1))
    assert 3.0 <= length <= 4.0
    assert 'NodePath("Splash:scale")' in clip and 'NodePath("Splash:position")' in clip
    # subtle: a few pixels, eased in and out, and it closes on its first key
    sx, sy = select_bg.BREATH_SCALE
    assert 1.0 < sx <= 1.005 and 1.0 < sy <= 1.015 and select_bg.SWAY_PX <= 4
    assert "PackedFloat32Array(-2.0" in clip
    for path in ("Splash:scale", "Splash:position"):
        keys = clip.split(f'NodePath("{path}")', 1)[1].split("\n}", 1)[0]
        vals = re.findall(r"Vector2\([^)]*\)", keys.split('"values":', 1)[1])
        assert len(vals) >= 3 and vals[0] == vals[-1], (path, vals)
    # the breath pivots on the figure's bottom centre, so the cut edge stays put
    splash = _node(text, "Splash")
    assert f"pivot_offset = Vector2({select_bg.num(RIGS[char].SELECT_FIGURE_X)}, 1080)" in splash
    assert f'texture = ExtResource("1_art")' in splash
    assert f'path="res://{char}/ui/select_closeup.png" id="1_art"' in text


def test_the_element_emitters_are_there_at_base_counts(char):
    text = _text(char)
    em = _emitters(text)
    assert 2 <= len(em) <= 5, sorted(em)
    assert EMITTERS[ELEMENT[char]] <= set(em), sorted(em)
    for name, block in em.items():
        amount = int(re.search(r"amount = (\d+)", block).group(1))
        assert 1 <= amount <= 40, (name, amount)
        assert "local_coords = true" in block, name
        lifetime = re.search(r"lifetime = ([\d.]+)", block).group(1)
        assert f"preprocess = {lifetime}" in block, name  # already in the air on pick
        tex = re.search(r'texture = SubResource\("([^"]+)"\)', block).group(1)
        assert f'[sub_resource type="GradientTexture2D" id="{tex}"]' in text, name
        assert re.search(r'color_ramp = SubResource\("Ramp_' + re.escape(name) + r'"\)', block), name
    assert sum(int(re.search(r"amount = (\d+)", b).group(1)) for b in em.values()) <= 80


def test_the_scene_is_loadable_without_scripts_or_base_textures(char):
    text = _text(char)
    assert 'type="Script"' not in text and "script =" not in text
    assert "res://images/" not in text and ".png" not in text.replace("select_closeup.png", "") \
        .replace("select_bg.png", "")
    exts = re.findall(r'\[ext_resource type="([^"]+)" path="([^"]+)"', text)
    assert exts == [("Texture2D", f"res://{char}/ui/select_closeup.png"),
                    ("Texture2D", f"res://{char}/ui/select_bg.png")]
    subs = text.count("[sub_resource")
    assert f"[gd_scene load_steps={subs + len(exts) + 1} format=3]" in text
    # every SubResource a node or resource names is declared
    declared = set(re.findall(r'\[sub_resource type="[^"]+" id="([^"]+)"\]', text))
    used = set(re.findall(r'SubResource\("([^"]+)"\)', text))
    assert used <= declared, used - declared
    # node order: backdrop under everything, the player last
    names = re.findall(r'\[node name="([^"]+)"', text)
    assert names[1] == "Backdrop" and names[-1] == "AnimationPlayer" and "Splash" in names


def test_text_only_and_small(char):
    # stage 1 adds no PNG: well under the 100 KB budget for all three
    assert len(_text(char).encode("utf-8")) < 12_000


def test_one_producer_build_pck_no_longer_writes_the_select_scenes(char):
    ps = BUILD.read_text(encoding="utf-8")
    assert f"'{char}\\ui\\char_select_bg_{char}.tscn'" not in ps
    assert f"${char}SelectArt" not in ps
    # the pack consumes the generated scene through the pck-src overlay, and
    # refuses to build without the close-up it draws
    assert "Copy-Item (Join-Path $pckSrc '*') -Destination $work -Recurse -Force" in ps
    closeup = "ui\\select_closeup.png" if char == "klee" else f"{char}\\ui\\select_closeup.png"
    assert f"'{closeup}'" in ps.split("foreach ($closeup in @(", 1)[1].split(")", 1)[0]


def test_each_rig_names_its_own_element_and_tint():
    tints = {c: RIGS[c].SELECT_TINT for c in RIGS}
    assert len(set(tints.values())) == 3
    for c, rig in RIGS.items():
        assert rig.SELECT_ELEMENT == ELEMENT[c]
        assert f"self_modulate = {klee_rig.color(rig.SELECT_TINT)}" in _node(_text(c), "Backdrop")
